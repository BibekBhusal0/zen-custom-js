import fs from "fs";
import path from "path";
import { $ } from "bun";
import { stripDeadMembers } from "./.github/scripts/strip-dead-members.js";

const getSubdirectories = (dir) => {
  return fs.readdirSync(dir).filter((file) => {
    const fullPath = path.join(dir, file);
    return (
      fs.statSync(fullPath).isDirectory() &&
      !file.startsWith(".") &&
      file !== "node_modules" &&
      file !== "dist"
    );
  });
};

const createBanner = (themePath) => {
  const theme = JSON.parse(fs.readFileSync(themePath, "utf-8"));

  let banner = `// ==UserScript==
// @name            ${theme.name}
// @description     ${theme.description}
// @author          ${theme.author}
// @version         ${theme.version}
// @lastUpdated     ${theme.updatedAt}
`;

  if (theme.ignoreCache !== false) {
    banner += `// @ignorecache\n`;
  }

  const standardKeys = [
    "id",
    "name",
    "description",
    "author",
    "version",
    "updatedAt",
    "tags",
    "fork",
    "preferences",
    "style",
    "scripts",
    "readme",
    "image",
    "createdAt",
    "ignoreCache",
  ];

  for (const key in theme) {
    if (!standardKeys.includes(key)) {
      const value = theme[key];
      if (Array.isArray(value)) {
        value.forEach((item) => {
          banner += `// @${key.padEnd(15)} ${item}\n`;
        });
      } else if (typeof value === "boolean") {
        if (value) banner += `// @${key}\n`;
      } else {
        banner += `// @${key.padEnd(15)} ${value}\n`;
      }
    }
  }

  banner += `// ==/UserScript==

// This file was automatically generated. Do not edit this file directly.
// Any changes made here will be overwritten.
// To make changes, please edit the source files in the repository:
// https://github.com/BibekBhusal0/zen-custom-js

`;

  return banner;
};

async function buildMod(themePath, entryFile, theme, isWatch = false) {
  const banner = createBanner(themePath);
  const outName = Object.keys(theme.scripts)[0];
  const format = outName.endsWith(".mjs") ? "esm" : "iife";

  const runBuild = async (options, label) => {
    try {
      const result = await Bun.build(options);
      if (!result.success) {
        for (const log of result.logs) console.error(`[${label}]`, log);
        throw new Error(`Build failed: ${label}`);
      }
      console.log(`Built ${label}`);
      // Bun only shakes top-level exports; strip dead object/class members
      // from the emitted bundle (dist only, never sources).
      try {
        const outPath = `./dist/${options.naming}`;
        const file = Bun.file(outPath);
        if (await file.exists()) {
          const original = await file.text();
          const { code, stripped } = stripDeadMembers(original);
          if (stripped > 0) {
            await Bun.write(outPath, code);
            console.log(`Stripped ${stripped} dead member(s) from ${label} (${original.length} -> ${code.length} bytes)`);
          }
        }
      } catch (stripErr) {
        console.warn(`[${label}] member stripping skipped: ${stripErr?.message ?? stripErr}`);
      }
    } catch (err) {
      if (err instanceof AggregateError) {
        for (const sub of err.errors) console.error(`[${label}]`, sub?.message ?? sub);
        throw new Error(`Build failed: ${label}`);
      }
      throw err;
    }
  };

  await runBuild(
    {
      entrypoints: [entryFile],
      outdir: "./dist",
      format,
      target: "browser",
      naming: outName,
      banner,
      minify: { syntax: true },
    },
    outName
  );

  if (isWatch) {
    // Watch rebuilds skip dead-member stripping (CLI has no hook for it).
    await $`bun build ${entryFile} --outdir ./dist --format ${format} --target browser --entry-naming ${outName} --banner "${banner}" --minify-syntax --watch`;
  }
}

async function build() {
  const target = process.env.TARGET;
  const isWatch = process.argv.includes("--watch");

  const mods = getSubdirectories(process.cwd());
  let modsToBuild = mods;
  if (target) {
    const normalizedTarget = target.replace(/-/g, "");
    const modsWithThemes = await Promise.all(
      mods.map(async (dir) => {
        const themePath = path.join(dir, "theme.json");
        if (!fs.existsSync(themePath)) return { dir, include: false };

        try {
          const theme = JSON.parse(await Bun.file(themePath).text());
          const normalizedThemeId = theme.id.replace(/-/g, "");
          return { dir, include: normalizedThemeId.includes(normalizedTarget) };
        } catch {
          return { dir, include: false };
        }
      })
    );
    modsToBuild = modsWithThemes.filter((m) => m.include).map((m) => m.dir);
  }

  let built = 0;
  const watchers = [];
  for (const dir of modsToBuild) {
    const themePath = path.join(dir, "theme.json");
    const entryFile = path.join(dir, "index.js");

    if (!fs.existsSync(themePath) || !fs.existsSync(entryFile)) {
      console.warn(`Skipped ${dir}: missing theme.json or index.js`);
      continue;
    }

    const theme = JSON.parse(await Bun.file(themePath).text());
    if (!theme.scripts) {
      console.warn(`Skipped ${dir}: no scripts key in theme.json`);
      continue;
    }
    if (isWatch) watchers.push(buildMod(themePath, entryFile, theme, true));
    else await buildMod(themePath, entryFile, theme, false);
    built++;
  }
  if (watchers.length) await Promise.all(watchers);

  if (target && built === 0) {
    throw new Error(`No mods matched TARGET="${target}"`);
  }
  console.log(`Done: built ${built} mod(s).`);
}

build().catch((err) => {
  console.error(err?.message ?? err);
  process.exit(1);
});
